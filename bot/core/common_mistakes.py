def find_mistakes(text: str) -> list:
    # пересечь текст юзера со всеми паттернами
    found = []
    text_lower = text.lower()

    for pattern, (error_text, advice, source) in TYPICAL_MISTAKES.items():
        if re.search(pattern, text_lower):
            found.append({
                "error": error_text,
                "advice": advice,
                "source": source,
            })

    return found
